#!/usr/bin/env python3
"""SIGKILL the real Swift snapshot/mapper at durable boundaries, then verify recovery.

All input is generated by the probe. ENOSPC is an injected OS error, explicitly
separate from filling an actual device volume. Never touches the App's data.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time


def digest(file):
    return hashlib.sha256(file.read_bytes()).hexdigest()


def invoke(binary, mode, directory, env=None, check=True):
    result = subprocess.run([str(binary), mode, str(directory)], capture_output=True, text=True,
                            timeout=60, env=env, check=False)
    if check and result.returncode:
        raise RuntimeError(result.stderr[-6000:])
    return json.loads(result.stdout) if result.returncode == 0 else result


def complete(value):
    assert value['snapshotReady'] and value['mappingReady'], value
    assert value['originalBooks'] == value['books'] == 1, value
    assert value['cachedChapters'] == value['offlineChapters'] == 2, value
    assert value['progressMapped'] and value['position'] == 4, value


def verify(binary):
    cases = []
    phases = ['snapshot.databaseCopied', 'snapshot.externalFileCopied', 'snapshot.beforePublish', 'snapshot.published',
              'mapping.sourcesMapped', 'mapping.booksMapped', 'mapping.cachesMapped', 'mapping.beforePublish', 'mapping.published',
              'adoption.beforeCopy', 'adoption.afterCopy', 'adoption.beforeCommit', 'adoption.committed']
    with tempfile.TemporaryDirectory(prefix='legado-migration-recovery-') as workspace:
        for index, phase in enumerate(phases):
            directory = Path(workspace) / ('legacy-migration-process-' + str(index))
            invoke(binary, 'seed', directory)
            original = digest(directory / 'legacy.sqlite3')
            if phase.startswith('adoption.'):
                complete(invoke(binary, 'prepare', directory))
            mode = 'adopt' if phase.startswith('adoption.') else 'prepare'
            environment = {**os.environ, 'LEGADO_MIGRATION_STOP_AT': phase}
            # Files avoid pipe deadlock; only synthetic probe diagnostics are captured.
            with (directory / 'probe.log').open('w') as log:
                process = subprocess.Popen([str(binary), mode, str(directory)], stdout=log, stderr=log, env=environment)
                try:
                    deadline = time.monotonic() + 60
                    marker = directory / 'reached-checkpoint'
                    while not marker.exists():
                        if process.poll() is not None:
                            raise RuntimeError('Probe exited before ' + phase + ': ' + (directory / 'probe.log').read_text()[-6000:])
                        if time.monotonic() > deadline:
                            raise RuntimeError('Probe did not reach ' + phase)
                        time.sleep(0.03)
                    assert marker.read_text() == phase
                    process.kill()
                    process.wait(timeout=10)
                    assert process.returncode < 0, process.returncode
                finally:
                    if process.poll() is None:
                        process.kill()
                        process.wait(timeout=10)
            if phase.startswith('adoption.'):
                before = invoke(binary, 'inspect-adoption', directory)
                committed = phase == 'adoption.committed'
                assert before == {'installed': int(committed), 'cachedChapters': 2 if committed else 0, 'receipt': committed}, (phase, before)
                resumed = invoke(binary, 'adopt', directory)
                assert resumed == {'installed': 1, 'cachedChapters': 2, 'receipt': True}, resumed
                assert invoke(binary, 'adopt', directory) == resumed
                assert digest(directory / 'legacy.sqlite3') == original
                cases.append({'phase': phase, 'sigkillObserved': True, 'atomic': True, 'resumed': True, 'originalUnchanged': True})
                continue
            before = invoke(binary, 'inspect', directory)
            assert before['mappingReady'] == (phase == 'mapping.published'), (phase, before)
            assert before['snapshotReady'] == (phase == 'snapshot.published' or phase.startswith('mapping.')), (phase, before)
            resumed = invoke(binary, 'prepare', directory)
            complete(resumed)
            repeated = invoke(binary, 'prepare', directory)
            assert repeated['reportDigest'] == resumed['reportDigest'], phase
            assert digest(directory / 'legacy.sqlite3') == original, phase
            cases.append({'phase': phase, 'sigkillObserved': True, 'resumed': True, 'idempotent': True, 'originalUnchanged': True})
        for index, phase in enumerate(['snapshot.externalFileCopied', 'mapping.beforePublish']):
            directory = Path(workspace) / ('legacy-migration-process-enospc-' + str(index))
            invoke(binary, 'seed', directory)
            original = digest(directory / 'legacy.sqlite3')
            failed = invoke(binary, 'prepare', directory, env={**os.environ, 'LEGADO_MIGRATION_ENOSPC_AT': phase}, check=False)
            assert isinstance(failed, subprocess.CompletedProcess) and failed.returncode != 0, phase
            assert 'Synthetic ENOSPC fault' in failed.stderr, failed.stderr[-3000:]
            assert not invoke(binary, 'inspect', directory)['mappingReady']
            complete(invoke(binary, 'prepare', directory))
            assert digest(directory / 'legacy.sqlite3') == original
            cases.append({'phase': phase, 'fault': 'injected ENOSPC', 'resumed': True, 'originalUnchanged': True})
    return {'version': 1, 'synthetic': True, 'sigkillCases': 13, 'injectedENOSPCCases': 2, 'cases': cases}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('probe', type=Path)
    parser.add_argument('--output', required=True, type=Path)
    arguments = parser.parse_args()
    result = verify(arguments.probe.resolve())
    arguments.output.parent.mkdir(parents=True, exist_ok=True)
    arguments.output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(result, ensure_ascii=False))
