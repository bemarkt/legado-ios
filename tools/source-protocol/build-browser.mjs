import { readFile, writeFile, mkdir, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import Ajv2020 from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const output = path.join(root, 'App/Resources/SourceRuntime');
const check = process.argv.includes('--check');
const schema = JSON.parse(await readFile(path.join(root, 'protocols/source-v1/schema.json'), 'utf8'));
const profileText = await readFile(path.join(root, 'protocols/source-v1/profile.json'), 'utf8');
const temporary = await mkdtemp(path.join(tmpdir(), 'legado-source-bundle-'));
try {
  const ajv = new Ajv2020({ strict: true, ownProperties: true, code: { source: true, esm: true } });
  ajv.addSchema(schema);
  const exports = Object.fromEntries(Object.keys(schema.$defs).map(name => [name, `${schema.$id}#/$defs/${name}`]));
  const validatorsFile = path.join(temporary, 'validators.mjs');
  await writeFile(validatorsFile, standalone(ajv, exports));
  const result = await build({
    absWorkingDir: root, entryPoints: [path.join(here, 'browser/inspector.mjs')], bundle: true, write: false,
    platform: 'browser', format: 'iife', globalName: 'SourceInspector', target: 'es2022',
    minify: false, legalComments: 'inline', nodePaths: [path.join(here, 'node_modules')],
    plugins: [{ name: 'portable-contracts', setup(builder) {
      builder.onResolve({ filter: /lib\/contracts\.mjs$|^\.\/contracts\.mjs$/ }, () => ({ path: 'contracts', namespace: 'portable' }));
      builder.onLoad({ filter: /.*/, namespace: 'portable' }, () => ({ resolveDir: here, contents: `
        import { createContracts } from './lib/contract-core.mjs';
        import * as validators from ${JSON.stringify(validatorsFile)};
        export const schema = ${JSON.stringify(schema)};
        export const profile = ${profileText};
        export const { validateValue, assertJSON } = createContracts(schema, profile, validators);
      ` }));
    } }]
  });
  // esbuild comments contain input paths. Remove temporary directory names for reproducible bytes.
  const inspector = result.outputFiles[0].text.replace(/^  \/\/ .*validators\.mjs$/gm, '  // Generated Schema validators');
  const licenses = ['# Embedded parser and validator licenses', '', 'Generated by tools/source-protocol/build-browser.mjs. esbuild is a build-only tool.', ''];
  for (const [name, file] of [['acorn', 'LICENSE'], ['ajv', 'LICENSE'], ['fast-uri', 'LICENSE'], ['fast-deep-equal', 'LICENSE'], ['json-schema-traverse', 'LICENSE'], ['require-from-string', 'license']]) {
    licenses.push(`## ${name}`, '', await readFile(path.join(here, 'node_modules', name, file), 'utf8'), '');
  }
  const files = { 'SourceInspector.js': inspector, 'profile.json': profileText, 'LICENSES.md': licenses.join('\n').trimEnd() + '\n' };
  if (!check) await mkdir(output, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const destination = path.join(output, name);
    if (check) {
      if (await readFile(destination, 'utf8') !== content) throw new Error(`${name} is stale; run npm run bundle`);
    } else await writeFile(destination, content);
  }
  console.log(`Browser inspector ${check ? 'verified' : 'generated'} (${Buffer.byteLength(inspector)} bytes)`);
} finally { await rm(temporary, { recursive: true, force: true }); }
